/**
 * Content translations — Arabic overlays for API-sourced data that the
 * backend stores in English only (workouts, meals, blog articles).
 *
 * Design decision: we keep the database single-locale (English) and ship
 * translations as a client-side dictionary. This keeps the API surface
 * unchanged and avoids migrations, at the cost of having to keep this
 * file in sync whenever the seed adds a new row. See translate-content.ts
 * for the hooks that apply these overlays at render time.
 *
 * Structure mirrors the shape of the generated API response types —
 * each overlay object contains only the string fields that need
 * translating. Unlisted fields (id, imageUrl, calories, duration, etc.)
 * are locale-agnostic and pass through unchanged.
 *
 * If a row's id is missing from the `ar` map, the consumer helpers will
 * fall through to the original English data — nothing crashes, the UI
 * just shows English for that one row until a translation is added.
 */

export type Locale = "en" | "ar";

