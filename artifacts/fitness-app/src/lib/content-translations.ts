/**
 * Public getters — return `undefined` when no overlay exists for the
 * requested locale + title, so the caller can fall through to the
 * original English data without branching on locale first. Titles are
 * normalized via `.trim()` so a seed typo like a trailing space won't
 * silently miss the dictionary.
 */
function normalizeTitle(title: string | null | undefined): string {
  return (title ?? "").trim();
}

export function getWorkoutOverlay(
  title: string,
  lang: Locale,
): WorkoutOverlay | undefined {
  if (lang !== "ar") return undefined;
  return WORKOUTS_AR[normalizeTitle(title)];
}

export function getMealOverlay(
  title: string,
  lang: Locale,
): MealOverlay | undefined {
  if (lang !== "ar") return undefined;
  return MEALS_AR[normalizeTitle(title)];
}

export function getArticleOverlay(
  title: string,
  lang: Locale,
): ArticleOverlay | undefined {
  if (lang !== "ar") return undefined;
  return BLOG_AR[normalizeTitle(title)];
}
